"use client";

import * as React from "react";
import { LogIn } from "lucide-react";
import { asset } from "@/lib/base-path";

/* --------------------------------------------------------------------------
   НЭВТРЭХ ДЭЛГЭЦ

   Энэ бол системийн ЦОРЫН ГАНЦ бүтэн дэлгэцийн харагдац: толгой ч,
   хажуугийн зурвас ч байхгүй. Шалтгаан нь энгийн — нэвтрээгүй хэрэглэгчид
   очих газар байхгүй. Цэс харуулаад товшилт бүрийг нь хаах нь хаалгыг
   нээлттэй мэт харуулж, дараа нь татгалзахтай адил.

   ⚠ **БИЧВЭР ЦӨӨН** (хэрэглэгчийн залруулга, 2026-09-15). Систем нэрээ
   хэлээд нэвтрэх боломжийг өгнө — өөр юу ч биш. Урьд нь байгууллагын нэр,
   хэрэглээний тайлбар, нууц үг хаана шалгагдах тухай тэмдэглэл гэсэн
   гурван нэмэлт блок байсныг хасав: нэвтрэхээс өөр сонголт байхгүй дэлгэц
   дээр тайлбар уншигддаггүй. Дахин бүү нэм.

   ⚠ **ДЭВСГЭР ЗУРАГ НЬ БАЙХГҮЙ Ч АЖИЛЛАНА.** Зураг нь
   `public/auth/background.webp` дээр сууна. Татагдаагүй тохиолдолд доор нь
   давхарлагдсан градиент харагдах тул дэлгэц хэзээ ч хоосон цагаан
   болохгүй. Зураг солих нь ганц файл солих ажил — код хөндөхгүй.

   ⚠ **ХҮРЭЭ НЬ ФАЙЛ ДОТРОО** (хэрэглэгчийн шийдвэр, 2026-09-15).
   Зотон 3060×1940, дотор нь 2560×1440 зураглал дөрвөн талаасаа 250px
   зайтай. Зай нь ижил зургийн бүдгэрүүлсэн хуулбар. CSS дээр гурван
   давхарга барьж байсныг хассан — тэнд хүрээний зузаан цонхны хэмжээнээс
   хамаарч хэлбэлздэг байв.

   ⚠ **БИЧВЭРИЙН ХӨВӨӨ ХУВИАР** (`lg:px-[12%]`). Зураглалын зүүн ирмэг нь
   зотоны өргөний 8.2%-д сууна; цонхны харьцаа зотоныхоос (1.58) өргөн
   байдаг тул зураг хэвтээгээр бүтэн багтаж, тэр 8.2% нь дэлгэцийн 8.2%
   болж хөрвөнө. Тогтмол пикселээр өгвөл нарийн цонхон дээр бичвэр
   хүрээн дээр гарна.

   ⚠ **БИЧВЭР ЗҮҮН ТАЛД СУУНА — ЗУРГААС БОЛЖ.** Зураг (2560×1440) нь
   нийслэлийн зураглал, зангилаануудыг өргөний **37%-иас баруун тийш**
   агуулж, зүүн гуравны нэг нь бүдгэрсэн уулархаг дэвсгэр. Бичвэр тэр
   хоосон хэсэгт сууна.
   ⚠ Зураг солигдож агуулга нь нөгөө тал руу шилжвэл ХОЁР зүйл ЗЭРЭГ
   эргэнэ: бичвэрийн тал (`justify-end`) ба хөшгийн чиглэл
   (`bg-gradient-to-l`). Ганцыг нь өөрчилвөл хөшиг гол агуулгыг дарна
   — нэг удаа ингэж эргүүлээд буцаасан.

   ⚠ **БИЧВЭР ЗУРАГ ДЭЭР УНШИГДАХ ЁСТОЙ.** Бичвэрийг зурган дээр ШУУД
   тавихгүй: хагас тунгалаг хөшиг (`scrim`) дээр сууна. Ингэснээр зураг
   цайвар ч, бараан ч байсан уншигдац тогтвортой.
   -------------------------------------------------------------------------- */

const BACKGROUND = asset("/auth/background.webp");

export function SignIn({
  onEnter,
  configured,
}: {
  onEnter: () => void;
  /** Аппын ID тохируулагдсан эсэх */
  configured: boolean;
}) {
  const [busy, setBusy] = React.useState(false);

  const enter = () => {
    setBusy(true);
    onEnter();
  };

  return (
    <div className="relative min-h-dvh w-full overflow-hidden bg-paper">
      {/*
        ЗУРАГ. Хүрээ нь ФАЙЛ ДОТРОО шатаагдсан (`background.webp` нь
        3060×1940 зотон дээр 2560×1440 зураглалыг дөрвөн талаасаа 250px
        зайтай суулгасан, зай нь ижил зургийн бүдгэрүүлсэн хуулбар).

        ⚠ Тиймээс энд ГАНЦ давхарга. Урьд нь CSS дээр гурван давхарга
        (бүдгэрсэн дэвсгэр + хөшиг + `inset`-тэй хүрээ) байсныг хассан.
        Файл дотор хийснээр хоёр зүйл шийдэгдэв: хүрээний зузаан дэлгэц
        бүрд ижил ХАРЬЦААТАЙ болж, мөн `bg-cover`-ийн хайчлалт эхлээд
        хүрээний зайг иддэг тул зураглал өөрөө хамгаалагдана.

        ⚠ 250px хүрээ нь САНАМСАРГҮЙ БИШ: цонхны харьцаа 1.76–2.08-ын
        хооронд хэлбэлздэг тул түүнээс нимгэн хүрээ дээр зураглалын
        ирмэг хасагдаж эхэлдэг (200px дээр зөөврийн компьютерт аль
        хэдийн хасагдана). Зураг солих бол `public/auth/README.md`-гийн
        тооцоог давтана.
      */}
      <div
        aria-hidden
        className="absolute inset-0 bg-paper-3 bg-cover bg-center"
        style={{ backgroundImage: `url("${BACKGROUND}")` }}
      />

      {/* Хөшиг нь ЗҮҮН тийш өтгөрнө: бичвэр тэнд сууж, баруун талын
          зураглал нээлттэй үлдэнэ */}
      <div
        aria-hidden
        className="absolute inset-0 bg-gradient-to-r from-paper via-paper/80 to-paper/25 lg:via-paper/70 lg:to-transparent"
      />
      {/* Нарийн дэлгэцэнд зураг ихээр хайчлагдаж бичвэрийн ард ямар ч
          хэсэг тохиолдож болох тул нэмэлт жигд хөшиг */}
      <div aria-hidden className="absolute inset-0 bg-paper/35 lg:bg-transparent" />

      <div className="relative flex min-h-dvh items-center px-8 py-14 sm:px-12 lg:px-[12%]">
        <div className="w-full max-w-[380px]">
          <h1 className="display text-[26px] leading-[1.2] text-ink">
            Байгаль орчны хяналтын
            <br />
            нэгдсэн систем
          </h1>

          <div className="ruler mt-4" />

          {configured ? (
            <button
              onClick={enter}
              disabled={busy}
              className="glow mt-6 flex w-full items-center justify-center gap-2 rounded-xs border border-(--moss)/45 bg-(--moss)/10 px-4 py-3 text-[13px] font-medium text-(--moss) transition-colors hover:bg-(--moss)/15 disabled:opacity-60"
            >
              <LogIn size={14} />
              {busy ? "Шилжиж байна…" : "Нэвтрэх"}
            </button>
          ) : (
            /* Тохиргоо дутуу үед товч харуулах нь утгагүй — дарвал алдаа
               л гарна. Хийх ёстой зүйлийг нь шууд хэлнэ */
            <div className="hatch mt-6 rounded-xs border border-dashed border-line-2 px-4 py-4">
              <p className="text-[12px] leading-relaxed text-ink-2">
                Нэвтрэлтийн тохиргоо дуусаагүй байна. Системийн админтай
                холбогдоно уу.
              </p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
