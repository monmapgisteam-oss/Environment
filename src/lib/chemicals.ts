const DATE_RE = /(\d{2,4})[./](\d{1,2})[./](\d{1,2})/g;

/** "2027.12.31" → 20271231. Задрахгүй бол `null` */
function parseDates(raw: string): { from: string | null; to: string | null } {
  const found: string[] = [];
  DATE_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = DATE_RE.exec(raw)) !== null) {
    /* Он дөрвөн оронтой байх ёстой. Богино бол бичилтийн алдаа —
       алгасахгүй, ХООСОН гэж тэмдэглэнэ (доорх `found` дараалал
       эхлэл/төгсгөлийн байрлалыг хадгална) */
    found.push(m[1].length === 4 ? `${m[1]}.${m[2].padStart(2, "0")}.${m[3].padStart(2, "0")}` : "");
  }
  return { from: found[0] || null, to: found[1] || null };
}

/** "2027.12.31" → 20271231 */
export function dateKey(d: string | null): number | null {
  if (!d) return null;
  const [y, m, day] = d.split(".").map(Number);
  return y * 10000 + m * 100 + day;
}

