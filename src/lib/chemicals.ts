export type Warehouse = {
  oid: number;
  /** Аж ахуйн нэгжийн нэр */
  company: string;
  /** Байршлын чөлөөт бичвэр — дүүрэг, хороо, тоот энд бичигдсэн */
  place: string;
  /**
   * Дүүргийн товчлол ({@link ../lib/repair-shops}-ийн `districtName`-ээр
   * задарна). 2023-т нэг бичлэг "Төв аймаг" гэж бичигдсэн — дүүрэг биш
   * тул толь бичигт байхгүй бөгөөд байгаагаар нь харагдана.
   */
  district: string;
  /** Зөвшөөрлийн эрхүүд */
  rights: string[];
  /** Эх бичвэр — дэлгэрэнгүйд бүтнээрээ */
  rightsRaw: string;
  /** Хадгалах газрын зориулалт — нэгэн жигд болгосон */
  storage: string;
  /** Нийт тоо хэмжээ, тонн. Бөглөгдөөгүй бол `null` — тэг БИШ */
  tons: number | null;
  /** Бодисын нэрс — давхардалгүй */
  substances: string[];
  /**
   * Бүртгэсэн бодисуудын ХИМИЙН БҮЛГҮҮД, давхардалгүй
   * ({@link classifySubstance}). Нэг агуулах олон бүлэгтэй байж болно.
   */
  groups: string[];
  /** Бодисын нэр, тоо хэмжээ — эх бичвэр */
  substancesRaw: string;
  /**
   * Задалсан мөрүүд. Нэр нь ДАВХАРДАЖ болно — эх сурвалж нэг бодисыг
   * өөр өөр тоо хэмжээгээр хэд хэдэн мөрд бичдэг ("Бетоны нэмэлт (245);
   * Бетоны нэмэлт (325)") тул `substances`-аас УРТ байх нь хэвийн.
   */
  items: SubstanceItem[];
  /** {@link items}-ийн тоо ямар нэгжтэй вэ. Тогтоогдохгүй бол `null` */
  qtyUnit: QtyUnit | null;
  /** Гэрчилгээний дугаар */
  certificate: number | null;
  /** Хүчинтэй хугацаа — эх бичвэр ("2023.01.12- 2027.12.31") */
  validityRaw: string;
  /** Задарсан эхлэл, төгсгөл ("2023.01.12"). Задрахгүй бол `null` */
  validFrom: string | null;
  validTo: string | null;
  registry: string;
  phone: string;
  lon: number;
  lat: number;
};

export type ChemicalData = {
  year: ChemicalYear;
  rows: Warehouse[];
  points: { oid: number[]; lon: number[]; lat: number[] };
  /** Бодис бүр хэдэн агуулахад бүртгэгдсэн — тоо буурахаар */
  substanceIndex: { name: string; group: string; n: number }[];
};

type Feature = {
  type: "Feature";
  properties: Record<string, unknown>;
  geometry: { type: "Point"; coordinates: [number, number] } | null;
};

function str(v: unknown) {
  return typeof v === "string" ? v.trim() : "";
}

export async function fetchChemicals(
  year: ChemicalYear,
  signal?: AbortSignal,
): Promise<ChemicalData> {
  const url =
    `${chemicalService(year)}/query?` +
    new URLSearchParams({
      where: "1=1",
      outFields: "*",
      outSR: "4326",
      orderByFields: "OBJECTID",
      f: "geojson",
    });
  const res = await fetch(url, { signal });
  if (!res.ok) throw new Error(`Химийн агуулахын бүртгэл татагдсангүй (${res.status})`);
  const json = (await res.json()) as { features?: Feature[] };

  const rows: Warehouse[] = [];
  const points = { oid: [] as number[], lon: [] as number[], lat: [] as number[] };
  const perSubstance = new Map<string, number>();

  for (const f of json.features ?? []) {
    const g = f.geometry;
    if (!g || !Array.isArray(g.coordinates)) continue;
    const [lon, lat] = g.coordinates;
    if (!Number.isFinite(lon) || !Number.isFinite(lat)) continue;

    const p = f.properties;
    const oid = Number(p["OBJECTID"]);
    const rightsRaw = str(p["Зөвшөөрлийн_төрөл"]);
    const validityRaw = str(p["Хүчинтэй_хугацаа"]);
    const { from, to } = parseDates(validityRaw);
    const substances = splitNames(str(p["Бодисын_нэрс"]));
    const groups = [...new Set(substances.map(classifySubstance))];

    const substancesRaw = str(p["Бодисын_нэрс__тоо_хэмжээ"]);
    const tonsRaw = p["Нийт_тоо_хэмжээ__тн_"];
    const tons =
      typeof tonsRaw === "number" && Number.isFinite(tonsRaw) ? tonsRaw : null;
    /* Тоо хэмжээний бичвэр хоосон бол нэрсийн жагсаалтад буцаж түшинэ —
       бодис нь бүртгэгдсэн, зөвхөн хэмжээ нь дутуу */
    const items = substancesRaw
      ? substancesRaw
          .split(";")
          .map((x) => x.trim())
          .filter(Boolean)
          .map(parseItem)
      : substances.map((name) => ({ name, qty: null }));

    rows.push({
      oid,
      company: str(p["Аж_ахуйн_нэгжийн_нэр"]) || "Нэр бүртгэгдээгүй",
      place: str(p["Байршил"]),
      district: str(p["Дүүрэг"]),
      rights: splitRights(rightsRaw),
      rightsRaw,
      storage: normalStorage(str(p["Хадгалах_газрын_зориулалт"])),
      tons,
      substances,
      groups,
      substancesRaw,
      items,
      qtyUnit: qtyUnitOf(items, tons),
      certificate:
        typeof p["Гэрчилгээний_дугаар"] === "number" ? p["Гэрчилгээний_дугаар"] : null,
      validityRaw,
      validFrom: from,
      validTo: to,
      registry: str(p["Регистр_гэрчилгээ"]),
      phone: str(p["Холбоо_барих_утас"]),
      lon,
      lat,
    });

    for (const s of substances) perSubstance.set(s, (perSubstance.get(s) ?? 0) + 1);

    /*
      Координатыг ЗАСАХГҮЙ. Гурван бичлэгийн цэг нь бүртгэсэн дүүргээсээ
      хол зайд (жишээ нь дүүрэг нь БГД боловч цэг нь хотоос 60 км зүүн
      тийш) байдаг. Аль нь зөв болохыг эх сурвалж хэлэхгүй тул
      байгаагаар нь үлдээв — цэгийг зөөвөл байхгүй баримт нэмнэ.
    */
    points.oid.push(oid);
    points.lon.push(lon);
    points.lat.push(lat);
  }

  /*
    Бодисын товьёог. Тоо буурахаар, тэнцвэл цагаан толгойн дарааллаар —
    эрэмбэ тогтмол байх ёстой (жил солиход жагсаалт үсэрч болохгүй).
  */
  const substanceIndex = [...perSubstance]
    .map(([name, n]) => ({ name, group: classifySubstance(name), n }))
    .sort((a, b) => b.n - a.n || a.name.localeCompare(b.name, "mn"));

  return { year, rows, points, substanceIndex };
}
