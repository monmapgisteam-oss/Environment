/** Таслагдсан бичилт — "Кали...", "Бу...", "..." */
const TRUNCATED = /(\.\.\.|…)\s*$/;

export function classifySubstance(name: string): SubstanceGroup {
  const x = name.toLowerCase();
  for (const [id, re] of GROUP_RULES) if (re.test(x)) return id;
  if (TRUNCATED.test(x)) return "cut";
  return "other";
}

export type QtyUnit = "t" | "kg";

export const QTY_UNIT_LABEL: Record<QtyUnit, string> = {
  t: "тонн",
  kg: "кг",
};

/** Бодисын нэг мөр — нэр ба тоо хэмжээ */
export type SubstanceItem = {
  name: string;
  /** Задрахгүй бол `null` */
  qty: number | null;
};

/**
 * "Полиакриламид (10)" → `{ name: "Полиакриламид", qty: 10 }`.
 *
 * Хаалт байхгүй бол бүтэн бичвэр нь нэр болж, тоо нь `null` үлдэнэ —
 * хаалтгүй мөрийг хаяхгүй, бодис нь бүртгэгдсэн хэвээр.
 */
function parseItem(part: string): SubstanceItem {
  const m = part.match(/^(.*?)\s*\(([^()]*)\)\s*$/);
  if (!m) return { name: part, qty: null };
  /* Мянгатын зай, таслалыг цэвэрлэнэ ("1 200", "1,200") */
  const v = Number(m[2].replace(/[\s,]/g, ""));
  return { name: m[1].trim() || part, qty: Number.isFinite(v) ? v : null };
}

/**
 * Бичлэгийн тоо хэмжээ ямар нэгжээр бичигдсэн бэ.
 *
 * Эх сурвалж нэгжээ хэлдэггүй тул задалсан тоонуудын НИЙЛБЭРийг
 * тонноор өгсөн нийт дүнтэй харьцуулж тогтооно.
 *
 * Нэг ч мөр задрахгүй бол `null` буцаана: дутуу нийлбэрийг харьцуулбал
 * тонноор бичсэнийг килограмм гэж андуурч болзошгүй.
 *
 * ХАРЬЦААГААР шалгана, зөрүүгээр биш — нийт дүн нь хоёр, гурван
 * оронтой бөөрөнхийлөгдсөн (0.2726 → 0.27) тул килограммын харьцаа яг
 * 1000 биш, 1010 ч гарч болно. Хоёр туйл нь мянга дахин зөрүүтэй учир
 * зурвасыг өргөн авсан ч хооронд нь андуурахгүй.
 */
export function qtyUnitOf(items: SubstanceItem[], tons: number | null): QtyUnit | null {
  if (!items.length || tons == null || tons <= 0) return null;
  let sum = 0;
  for (const it of items) {
    if (it.qty == null) return null;
    sum += it.qty;
  }
  const r = sum / tons;
  if (r >= 0.9 && r <= 1.1) return "t";
  if (r >= 900 && r <= 1100) return "kg";
  return null;
}

/** "А; Б; В" → ["А","Б","В"]. Хоосон, давхардсаныг хасна */
function splitNames(raw: string): string[] {
  const seen = new Set<string>();
  for (const part of raw.split(";")) {
    const t = part.trim();
    if (t) seen.add(t);
  }
  return [...seen];
}

/* --------------------------------------------------------------------------

   Хадгалах газрын зориулалт нь дөрвөн утгатай ч бичиглэл жигд бус
   ("Ажлын байр" ба "Ажлын Байр") тул бүлэглэхээс өмнө нэгэн жигд
   болгоно — эс тэгвээс нэг ангилал хоёр мөр болно.
   -------------------------------------------------------------------------- */

function normalStorage(raw: string) {
  if (!raw) return "Тэмдэглэгдээгүй";
  return raw.charAt(0).toUpperCase() + raw.slice(1).toLowerCase();
}

