export type Group = { key: string; label: string; total: number; rows: Datum[] };

/** Нэг бичлэгийн атрибутууд */
export type Row = Record<string, unknown>;

/** Шүүсэн мөрүүд дээр дахин тоолсон үр дүн */
export type Counted = {
  values: Datum[];
  groups?: Group[];
  /**
   * Ангилал бүрийн НЭМЭЛТ утга — зурвасын ХУВААРЬТ ОРОХГҮЙ.
   *
   * Өөр НЭГЖТЭЙ хоёр дахь тоо (бичлэгийн тоо ↔ талбайн га) тул
   * нэг хуваарьт оруулах нь "ижил нэгжтэй хэмжилт л нэг диаграмд
   * харьцуулагдана" дүрмийг зөрчинө — нэрийн ард бүдэг
   * бичвэрээр гарна ({@link Breakdown.note}).
   */
  notes?: Map<string, number>;
};

/** Нэг талбарын утгын задаргаа */
export type Breakdown = {
  /**
   * Диаграмын өөрийн түлхүүр.
   *
   * Нэг талбар хэд хэдэн диаграм төрүүлдэг (ангиллын тоо, тэр ангиллаар
   * хэмжсэн талбай …) тул `field` нь дангаараа давхардана.
   */
  id: string;
  /** Бүлэглэх талбар — цаг хугацааны диаграмд огнооны талбар өөрөө */
  field: string;
  /** Бүлэглэх талбарын нэр */
  label: string;
  kind: ChartKind;
  /**
   * Харьцуулалтын (`compare`) цуваануудын НИЙТЛЭГ нэр — "Мод бэлтгэсэн
   * талбай" (цуваа нь "2023", "2024" …). Гарчигт "Харьцуулалт"-ын оронд
   * гарна; нийтлэг хэсэггүй бол хоосон.
   */
  subject?: string;
  /** Харьцуулалтыг ОНООР ДАВХАРЛАСАН зурвасаар зурах ({@link LayerSet.measureCards}-ийн `stacked`) */
  stack?: boolean;
  /**
   * Хэмжигдэхүүний нэр — ангиллаас ӨӨР талбар хэмжигдэж байвал.
   *
   * Тоолол дээр хоосон: "хэдэн бичлэг" гэдэг нь талбарын нэр
   * шаарддаггүй.
   */
  measure?: string;
  /**
   * Нэг бичлэг ОЛОН ангилалд харьяалагдаж болох эсэх.
   *
   * ⚠ Ийм задаргааны нийлбэр нь бичлэгийн тооноос ИХ гарна (нэг талбай
   * хоёр дүүрэгт хамаарвал хоёуланд нь тоологдоно) бөгөөд тэр нь алдаа
   * биш. Гэхдээ газрын зургийн өнгө үүнээс ГАРАХГҮЙ: нэг дүрс хоёр
   * өнгөтэй байж чадахгүй тул аль нэгийг нь чимээгүй сонгох болно.
   */
  multi?: boolean;
  /**
   * Диаграмд ҮЛДСЭН мөрийн тоо — бүхнийг харуулаагүй үед.
   *
   * Нэрээр задлахад мөр нь бичлэгийн тоотой тэнцэнэ (хэдэн зуу байж
   * болно) тул хамгийн их утгатайг нь л үлдээнэ. Хураасан гэдгээ
   * гарчигтаа хэлэх ЁСТОЙ: дутуу жагсаалтыг бүтэн мэт харуулбал
   * диаграм өөрөө худал хэлнэ.
   */
  top?: number;
  /**
   * СЭЛГЭГЧИЙН АРД — суудал эзлэхгүй задаргаа (2026-11-11).
   *
   * Хэрэглэгч засварлагчаар давхаргад ШИНЭ ТАЛБАР нэмж ("Мөр нэмэх"),
   * түүнийг бөглөх тусам самбарт тэр талбарын диаграм ГАРАХ ёстой
   * (хэрэглэгч 2026-11-11: "тухайн field-ийн доторх мэдээлэл нэмэгдвэл
   * db шинэ chart үүсэх ёстой"). Урьд нь ангиллын диаграм дөрвөөр
   * ({@link MAX_CATEGORIES}), хэмжилтийнх дөрвөөр ({@link MAX_MEASURES})
   * хязгаарлагдаж, илүү гарсан нь ЧИМЭЭГҮЙ хасагддаг байв — шинэ талбар
   * оноогоор хуучныг түрэх, эсвэл огт гарахгүй үлдэх хоёрын аль нэг.
   *
   * Одоо хязгаараас хэтэрсэн задаргаа ХАСАГДАХГҮЙ, `behind` тэмдэгтэй
   * үлдэнэ: самбар түүнийг ижил хэлбэрийн нүүрний картын АРД давхарлаж
   * (ArcGIS Dashboards-ийн stacked element — хэрэглэгчийн санал: "pie
   * chart бол pie chart-ийнхаа ард орох, сэлгээд хардаг"), `tidy`
   * бүрдэлд тэнхлэгийн сэлгэгчид нэмнэ. Нүүрний картууд тогтвортой:
   * шинэ талбар хуучин диаграмыг хөдөлгөхгүй.
   *
   * ⚠ Хуваалт (`split`), хөндлөн хүснэгт, нэмэлт үзүүлэлт нь `behind`
   * задаргааг ТООЦОХГҮЙ — тэдгээр нүүрний бүтцийг тогтооно. Шүүлтүүрийн
   * цэс харин тооцно: шинэ талбараар шүүх боломж нээлттэй.
   */
  behind?: boolean;
  /** Мөрүүд — `compare`-аас бусад бүх төрөлд */
  values: Datum[];
  /**
   * НЭМЭЛТ ХЭМЖИЛТ — мөрийн ард, зурвасын хуваарьаас ГАДУУР.
   *
   * Нэг талбар ХОЁР диаграм төрүүлэх нь элбэг: ангиллын
   * БИЧЛЭГИЙН ТОО ба тэр ангиллаар хэмжсэн ТАЛБАЙ. Зэрэгцүүлбэл
   * ИЖИЛ дөрвөн ангиллыг хоёр удаа зурна (хэрэглэгч, 2026-09-24:
   * "хоёр бөгж давхардсан") — тиймээс хэмжилт нь тооллын
   * диаграмд шингэж, мөр бүрийн нэрийн ард бүдэг бичвэрээр гарна.
   *
   * ⚠ Зурвас нь ЗӨВХӨН `values`-ыг хэмжинэ — хоёр тоо ӨӨР НЭГЖТЭЙ
   * (коридорын самбартай нэг зарчим).
   * ⚠ Хоёр тоо ЭСРЭГ эрэмбэтэй байж болно (хамгийн олон
   * бичлэгтэй хэсэг нь хамгийн том талбайтай байх албагүй) — яг тэр
   * зөрүү нь мэдээлэл тул хоёуланг зэрэг харуулна.
   */
  note?: { label: string; unit?: string };
  /** Нэмэлт хэмжилтийн утга — {@link Counted.notes} */
  notes?: Map<string, number>;
  /** `compare`: ангилал бүрийн доор хэмжилтүүд эгнэнэ */
  groups?: Group[];
  /**
   * Бичлэг аль ангилалд харьяалагдах вэ.
   *
   * ШҮҮЛТ ба ДАХИН ТООЛОЛТ хоёулаа эндээс гарна: диаграм дээр товшсон
   * утга нь энэ функцийн буцаасан түлхүүртэй тааралдвал тэр бичлэг
   * үлдэнэ. Хоёр тусдаа дүрэм бичвэл диаграм дээр харагдах ангилал ба
   * шүүлтэд ордог ангилал эрт орой зөрнө (олон утгатай нүд, бүлэглэсэн
   * он зэрэгт ялангуяа).
   */
  keyOf: (row: Row) => string[];
  /**
   * Шүүсэн мөрүүдээр утгуудыг дахин тоолно.
   *
   * Диаграмын БҮТЭЦ (ямар талбар, ямар төрөл, ямар дараалал) шүүлтээс
   * ҮЛ ХАМААРНА — зөвхөн тоонууд өөрчлөгдөнө. Эс тэгвээс шүүлт тавих
   * бүрд диаграмууд өөрсдөө гарч, алга болж, самбар нь тогтворгүй
   * болно.
   */
  recount: (rows: Row[]) => Counted;
};

/**
 * ОГНООГООР ШҮҮХ ТЭНХЛЭГ ({@link LayerSet.dateBar}; хэрэглэгч 2026-10-22:
 * "ontoi datanuud deer deed hsgt n ognoogoor shuuh hsg").
 *
 * Давхаргын огноо агуулсан талбар бүр — `Date` төрөл, эсвэл он гэж
 * танигдсан тоон багана (`Date` байхгүй үед л). Диаграм нь
 * {@link YEAR_DENSITY}-оор нуугдсан байсан ч шүүлт БОЛОМЖТОЙ хэвээр.
 *
 * ⚠ Шүүлтийн түлхүүр нь хугацааны диаграмынхтай ИЖИЛ
 * (`<талбар>\0year`, `<талбар>\0month`) — нэг он диаграм дээр ч, дээд
 * товч дээр ч НЭГ төлөвөөр тодорно.
 * ⚠ Хоёроос цөөн ОН бөглөгдсөн талбар орохгүй: сонгох зүйл байхгүй.
 */
export type DateAxis = {
  field: string;
  label: string;
  yearOf: (row: Row) => number | null;
  /** Зөвхөн `Date` талбарт — тусдаа сарын багана сараа өөрөө хэлдэггүй */
  monthOf: ((row: Row) => number | null) | null;
  /** Бөглөгдсөн онууд, өсөхөөр */
  years: number[];
};

/**
 * Газрын зургийн шошгонд юу бичих вэ.
 *
 * Дүрс дээр бичих зүйл нь диаграмынхтай ИЖИЛ эх сурвалжаас гарах
 * ёстой: зураг дээр "Горхи-Тэрэлж 29,488 га" гэж бичээд диаграмд өөр
 * тоо гарвал аль нь зөв нь мэдэгдэхгүй болно. Тиймээс нэрийг нь
 * `nameField`-ээс, талбайг нь хэмжилтийн ЭХНИЙХЭЭС (диаграм мөн
 * түүнийг харуулдаг) авна.
 *
 * Аль нь ч олдохгүй бол `null` — шошгогүй дүрс нь буруу шошготойгоос
 * дээр.
 */
export type LayerLabels = {
  /** Нэрийн талбарын техникийн нэр */
  name: string | null;
  /** Хэмжилтийн талбар ба түүний нэгж */
  measure: { field: string; unit: string } | null;
};
