/**
 * Тусгай зөвшөөрөл тус бүрийн өнгө.
 *
 * Талбай бүр өөрийн өнгөтэй — газрын зураг дээрх хүрээг доорх диаграм,
 * хугацааны зурвастай нь холбоно. Өөрөөр хэлбэл өнгө нь хэмжигдэхүүн
 * биш ТАНИХ ТЭМДЭГ.
 *
 * Зургаан өнгө бүгд НЭГ ГЭР БҮЛД — платформын дата өнгө болох цэнхэрийн
 * (`--data`) эргэн тойронд. Өнгөний өнцөг 195–220 хэмийн нарийхан мужид
 * л хөдөлж, ялгаа нь ГОЛДУУ ГЭРЭЛТЭЛТЭЭР гарна (L 0.90 → 0.50).
 *
 * Учир нь: солонгон палитр (улаан, ногоон, шаргал, ягаан…) нь өнгө бүрд
 * өөр өөр УТГА байгаа мэт уншигдана — улаан нь аюул, ногоон нь сайн гэх
 * мэт. Энд бүх талбай ижил төрлийн зүйл тул тэдгээрийн ялгаа нь зөвхөн
 * "аль нь аль нь вэ" гэсэн танилт байх ёстой. Нэг өнгөний шатлал яг
 * үүнийг өгнө: хоорондоо ялгагдана, гэхдээ нэг зүйлийн зургаан хувилбар
 * гэдэг нь хадгалагдана.
 *
 * hex хэлбэрээр хадгалсан учир нь MapLibre `oklch()` уншдаггүй. Газрын
 * зураг ба диаграм ЯГ ижил утга хэрэглэх ёстой тул хоёуланд нь энэ
 * жагсаалт үйлчилнэ. Шинэ өнгө нэмэх бол мөн энэ мужид байлга.
 */
export const MINERAL_COLORS = [
  "#93f1f0", // oklch(0.90 0.09 195)
  "#4cdbe3", // oklch(0.82 0.12 200)
  "#00c3d5", // oklch(0.74 0.14 205)
  "#00a8c1", // oklch(0.66 0.14 210)
  "#008caa", // oklch(0.58 0.13 215)
  "#00708e", // oklch(0.50 0.11 220)
];

/**
 * Зөвшөөрлийн дугаараас өнгө.
 *
 * `id` нь эх сурвалжид тохиолдсон дараалал (1-ээс) тул ТОГТМОЛ — шүүлтүүр
 * солиход талбай өнгөө солихгүй.
 */
export function mineralColor(id: number): string {
  return MINERAL_COLORS[(id - 1) % MINERAL_COLORS.length];
}
