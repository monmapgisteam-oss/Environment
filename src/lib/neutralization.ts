import { arcgisJson } from "@/lib/arcgis";
import { HOSTING } from "@/lib/portal";
import { mnPointCode } from "@/lib/soil";

export const NEUTRALIZATION_SERVICE = `${HOSTING}/Hosted/X09_Saarmagjuulalt/FeatureServer/2`;

/**
 * Хэмжигдсэн 10 хүнд метал.
 *
 * Дараалал нь ТОГТМОЛ: доорх `c` (агууламж) ба `pi` (индекс) массивын
 * индекс энэ жагсаалттай яг таарна. Дараалал солих бол хоёуланг нь
 * дагуулж солино.
 */
export const ELEMENTS = [
  { id: "as", symbol: "As", name: "Хүнцэл" },
  { id: "cd", symbol: "Cd", name: "Кадми" },
  { id: "co", symbol: "Co", name: "Кобальт" },
  { id: "cr", symbol: "Cr", name: "Хром" },
  { id: "cu", symbol: "Cu", name: "Зэс" },
  { id: "mo", symbol: "Mo", name: "Молибден" },
  { id: "ni", symbol: "Ni", name: "Никель" },
  { id: "pb", symbol: "Pb", name: "Хар тугалга" },
  { id: "sr", symbol: "Sr", name: "Стронци" },
  { id: "zn", symbol: "Zn", name: "Цайр" },
] as const;

export type NeutralPoint = {
  oid: number;
  /** Эх сурвалжийн дугаарлалт (№) */
  no: number;
  /**
   * Цэгийн код — "BZD-9". Угтвар нь дүүргийн товчлолтой таарч байгаа
   * (BZD → Баянзүрх, KHD → Хан-Уул) ч эх сурвалж үүнийг тайлбарлаагүй
   * тул кодыг задлахгүй, байгаагаар нь харуулна.
   */
  code: string;
  lon: number;
  lat: number;
  /*
    Дүүрэг, хороо нь орон зайн нэгтгэлээс ирнэ. Эх сурвалж дүүргийг
    "Баянзүрх дүүрэг" гэж дагавартай бичдэг ч платформын бусад бүх
    самбар дагаваргүй нэр хэрэглэдэг тул энд ч дагаваргүй.
  */
  district: string;
  khoroo: number;
  /** Хорооны монгол нэр (`kh_mon`) — газрын зургийн шошго энэ талбараас (хэрэглэгчийн шийдвэр, 2026-09-17) */
  khMon: string;
  /** Элемент тус бүрийн агууламж, мг/кг — {@link ELEMENTS}-ийн дарааллаар */
  c: (number | null)[];
  /** Элемент тус бүрийн бохирдлын индекс — нэгжгүй, дэвсгэр түвшинд харьцуулсан */
  pi: (number | null)[];
};

/**
 * Дөрвөн цэгийн бүрэн хэмжилт.
 *
 * `null`-ийг ТЭГ гэж үзэхгүй. Кадмийн индекс дөрвөөс гуравт, молибдений
 * индекс BZD-144 дээр хоосон байна.
 *
 * Хөрсний мониторингийн ижил цэгүүд дээр эдгээр талбар нь яг 0 гэж
 * бичигдсэн байдаг (`Cd_PI` = 0, `Mo_PI` = 0) — өөрөөр хэлбэл энэ
 * давхаргыг бэлтгэхдээ 0-ийг хоосон болгосон байна. Тэгш тэг нь
 * "агууламж дэвсгэрийн 0 дахин" гэсэн утгагүй утга тул хоосон гэж
 * үзэх нь илүү зөв — гэхдээ энэ нь ХЭМЖИГДЭЭГҮЙ гэсэн НОТЛОГДСОН
 * баримт биш, эх сурвалжийн 0-ийг ингэж уншсан хэрэг.
 */
/**
 * Дөрвөн цэгийг татаж, элементийн массивыг ELEMENTS-ийн ДАРААЛЛААР угсарна.
 *
 * ⚠ Дараалал нь гэрээ: `c` (агууламж) ба `pi` (индекс) массивын индекс
 * `ELEMENTS`-тэй яг таарна. Тиймээс талбарын нэрийг тэр жагсаалтаас
 * гаргана — гараар бичвэл нэг өдөр зөрнө.
 *
 * ⚠ `null` нь ХЭМЖИГДЭЭГҮЙ, тэг БИШ (кадмийн индекс дөрвөөс гуравт,
 * молибдений индекс нэгд нь бөглөгдөөгүй).
 */
export async function fetchNeutralization(): Promise<NeutralPoint[]> {
  const url =
    `${NEUTRALIZATION_SERVICE}/query?` +
    new URLSearchParams({
      where: "1=1",
      outFields: "*",
      /* Геометр нь UTM 48N-д проекцлогдсон ч уртраг, өргөрөг нь
         ТАЛБАР болж бичигдсэн тул геометр татах шаардлагагүй */
      returnGeometry: "false",
      orderByFields: "objectid",
      f: "json",
    });

  const json = await arcgisJson<{ features?: { attributes: Row }[] }>(
    url,
    "Саармагжуулалт",
  );

  return (json.features ?? []).map((f) => {
    const a = f.attributes;
    return {
      oid: Number(a.objectid),
      no: Number(a.f_),
      code: mnPointCode(String(a["цэгийн_дугаар"] ?? "")),
      lon: Number(a["уртраг"]),
      lat: Number(a["өргөрөг"]),
      /* Эх сурвалж "Баянзүрх дүүрэг" гэж дагавартай бичдэг ч платформын
         бусад бүх харагдац дагаваргүй — нэг л хэлбэрт оруулна */
      district: String(a["duureg"] ?? "").replace(/\s*дүүрэг\s*$/u, "").trim(),
      khoroo: Number(a["khorooid"]),
      khMon: String(a["kh_mon"] ?? "").trim(),
      c: ELEMENTS.map((e) => numOrNull(a[`${e.id}_агууламж__мг_кг`])),
      pi: ELEMENTS.map((e) => numOrNull(a[`${e.id}_бохирдлын_индекс`])),
    };
  });
}

type Row = Record<string, string | number | null>;

function numOrNull(v: string | number | null | undefined): number | null {
  return typeof v === "number" && Number.isFinite(v) ? v : null;
}

/**
 * Дэвсгэр түвшин.
 *
 * Бохирдлын индекс нь хэмжигдсэн агууламжийг дэвсгэр агууламжид харьцуулсан
 * харьцаа тул 1 гэдэг нь тодорхойлолтоороо "дэвсгэр түвшинтэй тэнцүү".
 * Энэ бол таамаг биш — хөрсний самбарын PI-тай ижил утга.
 */
export const PI_LIMIT = 1;

/*
  Индексийн зэрэглэл, өнгө нь ХӨРСНИЙ САМБАРТАЙ НЭГ эх үүсвэрээс
  ({@link ./soil}) — Håkanson (1980)-ийн олон улсын ангилал. Хоёр
  самбар нэг датаны дээр суудаг тул тэдгээр нь ЗААВАЛ ижил хуваарь
  хэрэглэнэ; тусад нь тодорхойлбол нэг л утга хоёр өөр зэрэглэлтэй
  харагдана.
*/
export { PI_CLASSES, piClass, piColor } from "@/lib/soil";

/* --------------------------------------------------------------------------
   Хэмжигдэхүүн сонгох

   Элемент бүр АГУУЛАМЖ ба ИНДЕКС хоёуланг нь агуулна — хөрсний самбараас
   ялгаатай нь энд хоёулаа НЭГ цэгийнх тул чөлөөтэй сэлгэж болно (тэнд
   хоёр өөр жилийн хэмжилт байсан бөгөөд харьцуулах боломжгүй байв).
   -------------------------------------------------------------------------- */

export const MEASURES = [
  { id: "pi", label: "Бохирдлын индекс", unit: "" },
  { id: "c", label: "Агууламж", unit: "мг/кг" },
] as const;

export type MeasureId = (typeof MEASURES)[number]["id"];

/** Цэгийн тухайн элементийн утга — хэмжигдээгүй бол `null` */
export function valueOf(p: NeutralPoint, element: number, m: MeasureId) {
  return (m === "pi" ? p.pi : p.c)[element];
}

/** Дэвсгэр түвшнээс хэтэрсэн хэмжилтийн тоо */
export function exceedCount(p: NeutralPoint) {
  return p.pi.filter((v): v is number => v != null && v >= PI_LIMIT).length;
}

/** Хэмжигдсэн (хоосон биш) индексийн тоо */
export function measuredCount(p: NeutralPoint) {
  return p.pi.filter((v) => v != null).length;
}
