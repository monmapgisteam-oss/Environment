/**
 * Цэс бүрийн бүрдэл.
 *
 * ⚠ Бүрдлүүд МОДУЛИЙН ТҮВШИНД үүснэ, зурагдалт бүрд БИШ. Самбарын
 * татах эффект нь `set`-ээс хамаардаг тул шинэ объект бүр дахин
 * татуулж, төгсгөлгүй давталт үүсгэнэ.
 *
 * ⚠ Түлхүүр нь цэс бүрд ӨӨР: `Columns`-ийн өргөн, шүүлтүүрийн сонголт
 * түүгээр хадгалагддаг тул хуваалцвал цэсүүд бие биенийхээ төлөвийг
 * дарж бичнэ.
 *
 * Хоёр цэс НЭГЭЭС ОЛОН давхаргатай: усны хамгаалалтын гурван бүс нэг
 * зурагт хамт харагдах ёстой (тэдгээр нь нэг системийн гурван шат),
 * булгийн бүс хоёр оны хувилбартай. Тиймээс `openAll` нь давхаргын
 * тооноос ҮЛ ХАМААРНА — цэс нээгдэхэд бүгд асна.
 */
function tab(key: string, title: string, layers: readonly string[]): LayerSet {
  return {
    key: `nogoon-${key}`,
    title,
    layers,
    names: NAMES,
    hues: layers.map((id) => HUES[AT[id] ?? 0]),
    /* Порталаас гадуурх хаягийг бүрдэл бүрд дамжуулна — самбар нь
       давхарга хаана байгааг мэдэх шаардлагагүй */
    services: { [SURVEY]: SURVEY_URL },
    skipField: SKIP_FIELD,
    openAll: true,
    /* Цэс бүр нэг сэдвийн давхаргатай тул шошго нь зургийг дарахгүй —
       харин ч "энэ бүс юу вэ" гэдэгт шууд хариулна */
    labels: true,
  };
}

