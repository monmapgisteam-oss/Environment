/**
 * Порталын давхаргын НЭГДСЭН ХӨДӨЛГҮҮР.
 *
 * `environment.ub.gov.mn` порталд хостлогдсон feature service бүр ижил
 * зан төлөвтэй: токен шаардана, бүтцээ өөрөө хэлдэг, талбарын нэр нь
 * жижиг үсэгтэй. Тиймээс хэлтэс бүрд кодыг хуулахын оронд ГАНЦ
 * хөдөлгүүр бичиж, хэлтэс нь зөвхөн БҮРТГЭЛЭЭ (`LayerSet`) өгнө.
 *
 * ⚠ **БҮГД ТОКЕН ШААРДАНА.** Давхаргууд `organization` түвшинд
 * хуваалцагдсан тул нэвтрээгүй хөтөч юу ч татахгүй. Токеныг
 * `lib/arcgis.ts` өөрөө хавсаргана — энд тусгай зүйл хийх шаардлагагүй.
 *
 * ⚠ **ТАЛБАРЫГ УРЬДЧИЛЖ ТААМАГЛААГҮЙ.** Давхаргын бүтцийг эх
 * сурвалжаас ӨӨРӨӨС нь уншина (`fetchLayerInfo`): нэр, геометрийн
 * төрөл, бичлэгийн тоо, талбарын жагсаалт бүгд үйлчилгээний өөрийн
 * тодорхойлолтоос ирнэ. Ингэснээр нэр, талбар нь өөрчлөгдвөл самбар
 * дагаж өөрчлөгдөнө; таамагласан талбарын нэр хэзээ ч кодод үлдэхгүй.
 */

import { arcgisJson } from "@/lib/arcgis";
import { HOSTING } from "@/lib/portal";

/** ~10 метрийн ерөнхийлөлт (градусаар) */
const OFFSET = 0.0001;

/** Нэг удаад татах дээд бичлэг */
const PAGE = 2000;

/**
 * Давхаргын бүртгэл.
 *
 * `id` нь үйлчилгээний нэр — хадгалалтын түлхүүр, дүрслэлийн дугаар
 * хоёуланд нь хэрэглэгдэнэ. Харагдах НЭР энд БИЧИГДЭЭГҮЙ: түүнийг
 * үйлчилгээ өөрөө хэлдэг тул ажиллах үед уншина.
 *
 * Эхний хоёр (`O01_…`) нь нэг сэдвийн хоёр тал (талбай ба хилийн цэг),
 * үлдсэн зургаа (`O03_…`) нь өөр сэдэв — угтварыг эх сурвалж өгсөн
 * бөгөөд утгыг нь тайлбарлаагүй тул БҮЛЭГЛЭХГҮЙ, дарааллыг нь л
 * хадгална.
 */
/**
 * Нэг хэлтсийн ДАВХАРГЫН БҮРТГЭЛ.
 *
 * Хэлтэс бүр өөрийн жагсаалт, нэр, өнгө, хасалтын дүрмээ энд өгнө —
 * бусад бүх зүйл (татац, задаргаа, диаграм, шүүлт) хуваалцагдана.
 */
export type LayerSet = {
  /** Хадгалалтын түлхүүрийн орон зай (`localStorage`, `Columns`) */
  key: string;
  /**
   * Шүүлтүүрийн мөрөнд гарах гарчиг.
   *
   * ⚠ Урьд нь энэ нь "Ойн давхарга" гэж КОДОД БИЧИГДСЭН байсан тул
   * самбарыг амьтан, ногоон бүсийн хэлтэс хуваалцмагц тэдгээр дээр
   * ч "Ойн давхарга" гэж гарч байв. Хэлтэс бүр өөрийнхөө нэрийг өгнө.
   */
  title?: string;
  /** Үйлчилгээний нэрс — жагсаалтын ДАРААЛАЛ нь өнгөний дараалал мөн */
  layers: readonly string[];
  /**
   * ПОРТАЛААС ГАДУУРХ давхаргын БҮТЭН хаяг — `id` → `FeatureServer`.
   *
   * Давхаргууд ихэвчлэн `environment.ub.gov.mn`-ий `Hosted` доор
   * сууна ({@link layerService}) ч бүгд биш: Survey123-ийн маягтууд
   * ArcGIS Online дээр үүсдэг бөгөөд тэндээс нь зөөх боломжгүй
   * тохиолдол бий.
   *
   * ⚠⚠ **ТОКЕН ХӨНДЛӨН ГАРАХГҮЙ.** Сессийн токен нь зөвхөн
   * `environment.ub.gov.mn`-д хүчинтэй ({@link SECURED_HOSTS}) —
   * ArcGIS Online бол ӨӨР систем, өөр байгууллага. Тиймээс энд
   * бичигдэх үйлчилгээ нь **нээлттэй хуваалцагдсан байх ЁСТОЙ**;
   * үгүй бол давхарга 499 буцааж, самбар алдааг нь мөрөндөө ил
   * харуулна (чимээгүй тэг БИШ — `arcgisJson` барина).
   */
  services?: Record<string, string>;
  /**
   * ХАРАГДАХ НЭР.
   *
   * Үйлчилгээ өөрийгөө `O01_THGN_polygon` гэж нэрлэдэг — энэ нь
   * серверийн нэр бөгөөд хэрэглэгчид юу ч хэлэхгүй. Самбар дээр латин
   * товчлол гаргах нь платформын "товчлол задална" дүрмийг ч зөрчинө.
   *
   * ⚠ Эдгээр нь ОРЧУУЛГА биш, үйлчилгээний нэрийн задаргаа. Утгыг нь
   * эх сурвалж тайлбарлаагүй тул нэрнээс нь ЦААШ таамаглахгүй.
   *
   * Энд бичигдсэн нэр нь эх сурвалжийн хуудсанд (`lib/sources.ts`) мөн
   * хэрэглэгддэг — хоёр газар тусад нь бичвэл эрт орой зөрнө.
   */
  names: Record<string, string>;
  /**
   * Өнгөний ӨНЦГҮҮД — давхарга бүрд нэг.
   *
   * Хэлтсийн `--d-*` өнгөний эргэн тойронд сонгоно: давхаргууд нэг
   * зураг дээр нийлдэг тул тэднийг ялгах ёстой ч хэлтсийнхээ өнгөний
   * гэр бүлээс салах ёсгүй.
   */
  hues: number[];
  /**
   * Давхаргуудыг НЭЭХЭД НЬ шууд асаах эсэх.
   *
   * Олон давхаргатай нийлмэл бүрдэл ХООСОН эхэлнэ — юуг нь харахыг
   * хэрэглэгч сонгоно. Харин сэдэв тус бүрд зориулсан цонх дээр
   * сонгох зүйл байхгүй: тэнд байгаа бүх давхарга тэр сэдвийнх тул
   * хоосон зураг гаргаад гараар асаалгах нь утгагүй.
   *
   * ⚠ Энэ нь давхаргын ТООНООС гардаггүй — БҮРТГЭЛИЙН шийдвэр.
   * "Нэг давхаргатай бол асаа" гэсэн дүрэм нь хоёр, гурван давхаргатай
   * сэдвийн цонхыг (усны хамгаалалтын гурван бүс гэх мэт) хоосон
   * үлдээж байв.
   */
  openAll?: boolean;
  /**
   * Давхаргууд ХАРИЛЦАН ҮГҮЙСГЭХ — нэг удаад ЗӨВХӨН НЭГ.
   *
   * Шүүлтүүрийн мөрийн эхэнд товчны хос гарч, зүүн талын сонгох
   * багана БАЙХГҮЙ. `openAll`-тай адил жагсаалтыг авдаг ч утга нь
   * эсрэг: тэр нь "бүгд нэг зурагт нийлнэ", энэ нь "нэгийг нь
   * сонгоно".
   *
   * ⚠ ХЭЗЭЭ хэрэглэх вэ: давхаргууд нь НЭГ сэдвийн ХОЁР ӨӨР
   * бүртгэл байж, зэрэг харах нь утгагүй үед. Хяналтын хэлтсийн
   * энгийн ба аюултай хог хаягдал нь яг тийм — нэг нь хотын хогийн
   * цэг (талбай, эзэмшигч), нөгөө нь тусгай зөвшөөрлийн бүртгэл
   * (ангилал, хугацаа). Тэдний талбар огт давхцахгүй тул нэг зурагт
   * нийлүүлэхэд задаргаанууд нь хоёр тусдаа бүлэг болж, шүүлтүүрийн
   * мөр хоёр дахин уртасдаг.
   *
   * ⚠ Он сонгох товчтой НЭГ гэр бүл (хөрсний мониторинг, ерөнхий
   * үнэлгээ): энэ нь ШҮҮЛТҮҮР БИШ, "юуг харах вэ" гэсэн эх
   * сурвалжийн сонголт тул шүүлтүүрүүдээс тусад нь, гарчгийн хажууд
   * сууна.
   *
   * ⚠ `openAll` өгөгдсөн бол энэ талбар үл тоомсорлогдоно.
   */
  exclusive?: boolean;
  /**
   * ЭХЭНД АСААЛТТАЙ давхаргууд — сонгох жагсаалт ХЭВЭЭР үлдэнэ.
   *
   * `openAll`-аас ялгаатай: тэр нь жагсаалтыг бүхэлд нь авдаг бол энэ
   * нь олон давхаргатай цонхыг хоосон биш, зарим давхаргатай нээнэ
   * (хэрэглэгчийн шийдвэр, 2026-09-17, үнэлгээний хэлтэс: "анхнаасаа
   * аль нь check байя"). Хоосон зураг дээр заавар бичихийн оронд
   * хамгийн төлөөлөх давхаргыг шууд харуулна; бусдыг нь хэрэглэгч
   * нэмнэ. `openAll` өгөгдсөн бол энэ талбар үл тоомсорлогдоно.
   */
  open?: readonly string[];
  /**
   * Газрын зургийн ШОШГО нээхэд нь шууд асах эсэх.
   *
   * Ойн хэлтэс дээр шошго АНХНААСАА унтраалттай: тэнд найман давхарга
   * нэг зурагт нийлдэг бөгөөд олон хэсэгтэй дүрс (100 метрийн зурвас)
   * хэсэг болгондоо шошго авдаг тул алсаас зураг бүхэлдээ бичвэрээр
   * дүүрдэг.
   *
   * Сэдэв тус бүрд зориулсан цонх дээр тэр эрсдэл БАГА: нэг, хоёр
   * давхарга л байдаг бөгөөд шошго нь "энэ юу вэ" гэдэгт шууд
   * хариулна. Тиймээс энэ нь давхаргын тооноос биш БҮРТГЭЛИЙН
   * шийдвэр.
   */
  labels?: boolean;
  /**
   * ХЭМЖИЛТЭД ОРОХГҮЙ талбар — нэрээр нь.
   *
   * Хэлтсийн шийдвэр (жишээ нь дам гаргасан утга) тул датаны шинж
   * БИШ: утга нь эх сурвалжид, бичлэгийн дэлгэрэнгүйд хэвээр байна.
   */
  skipMeasure?: RegExp;
  /**
   * ДҮРСЛЭЛД ОГТ ОРОХГҮЙ талбар — нэрээр нь.
   *
   * {@link skipMeasure} нь зөвхөн хэмжилтийг хасдаг бол энэ нь
   * талбарыг БҮХЭЛД НЬ (ангилал, нэр, хугацаа) хасна.
   *
   * ⚠ Зориулалт нь БИЧЛЭГИЙН ТУХАЙ метадата: ус ашиглагчийн гэрээний
   * `has_xy` ("Солбицол бүртгэгдсэн эсэх") нь усны тухай ЮУ Ч
   * ХЭЛЭХГҮЙ — зөвхөн тэр мөрийн координат бөглөгдсөн эсэхийг
   * хэлнэ. Гэтэл утга нь 113/105 гэж бараг төгс тэнцвэртэй тул
   * энтропийн оноогоор БҮХ бодит задаргааг түрүүлж, "Ус ашиглах
   * хэмжээ — Солбицол бүртгэгдсэн эсэх" гэсэн утгагүй диаграм
   * зурагдаж байв (2026-09-17).
   *
   * Ийм талбарыг ерөнхий дүрмээр таних боломжгүй: "… эсэх" гэсэн
   * бусад талбар (хамгаалалтын бүс тогтоосон эсэх, гэрээг дүгнүүлсэн
   * эсэх) нь ЖИНХЭНЭ задаргаа. Тиймээс хэлтсийн БҮРТГЭЛД сууна.
   */
  skipField?: RegExp;
  /**
   * ДИАГРАМЫН ЦЭГЦ — бодит датан дээр илэрсэн гурван шуугианыг цэвэрлэнэ
   * (2026-09-25, ногоон бүсийн 18 давхаргыг токеноор шалгасны дараа).
   *
   * 1. **Бичиглэлийн хувилбарыг нэгтгэнэ** — "Айлтай" ба "айлтай" нь
   *    ХОЁР ангилал болж, намгархаг газрын дөрвөн бодит утга ДОЛООН
   *    зурвас болж байв. Нэгтгэлт нь ТАТАХ мөчид хийгдэх тул диаграм,
   *    шүүлтүүр, бичлэгийн дэлгэрэнгүй гурвуулаа нэг хэлбэр харуулна.
   * 2. **Хоосон хугацааны цувааг хаяна** — суурилуулсан он нь 30
   *    бичлэгийг 11 жилд тарааж, ихэнх багана нь тэг байв. Ийм цуваа
   *    чиг хандлага БИШ, шуугиан.
   * 3. **Нэрийн баганаар хэмжсэн диаграмыг НЭГЭЭР хязгаарлана** —
   *    гадаргын усны бүртгэлд "Нэр / Өндөр", "Нэр / pH", "Нэр / TDS",
   *    "Нэр / Температур" гэсэн ДӨРӨВ зэрэг гарч, нэг давхарга АРВАН
   *    ХОЁР диаграмтай болж байв. Нэр бүр НЭГ бичлэгтэй тул тэдгээрийн
   *    "дундаж" нь задаргаа биш, түүхий утгын жагсаалт.
   * 4. **Хоёр, гурван утгатай ТООН талбар нь ангилал** — булгийн бүсийн
   *    `distance` (50 ба 200) нь тоон тул хэмжилт гэж үзэгдэж, 495
   *    бичлэгтэй давхарга НЭГ Ч диаграмгүй үлддэг байв.
   *
   * ⚠ Бүртгэлийн тэмдэг болгосон нь санаатай: эдгээр нь хуваалцсан
   * хөдөлгүүрийн зан төлөвийг өөрчилдөг тул ой, амьтан, үнэлгээний
   * хэлтсийг ХӨНДӨХГҮЙ. Тэдгээр дээр шалгаж баталсны дараа асаана.
   */
  tidy?: boolean;
  /**
   * ҮЗҮҮЛЭЛТИЙН ЗУРВАС ГАРАХ ЭСЭХ (анхдагчаар гарна).
   *
   * ⚠⚠ Ногоон бүсийн хэлтэс дээр `false` (2026-09-29, хэрэглэгч:
   * "НБАХ-ийн бусад цэсүүдээс бас эдгээрийг нь хасъя"). Тэнд зурвас
   * нь "Шүүлтэд тохирох бичлэг · Талбай, га" гэсэн хоёр тоог
   * харуулдаг ч хоёулаа ӨӨР ГАЗАР аль хэдийн бий: бүсийн карт,
   * таних тэмдэг, давхаргын тууз, диаграмын толгойн нийт дүн.
   * Санхүүгийн хэлтэст ЯГ ИЖИЛ шалтгаанаар зурвас хасагдсан
   * (2026-09-10) — дүрэм нэг: НЭГ ТООГ ХОЁР ГАЗАР БИЧИХГҮЙ.
   *
   * ⚠⚠ `tidy`-Д УЯХГҮЙ: ой, амьтан, үнэлгээний хэлтэс дээр `tidy`
   * хожим асаж болзошгүй (дээрх тэмдэглэлийг үзнэ үү) бөгөөд тэдэнд
   * зурвас ХЭРЭГТЭЙ — ойн хэсэглэлийн "7,699 бичлэг" өөр хаана ч
   * гардаггүй. Тиймээс тусдаа туг, хэлтсийн ӨӨРИЙН шийдвэр.
   */
  overview?: boolean;
  /**
   * ДАВХАРГА СОНГОХ ЦЭСНИЙ НЭР — шүүлтүүрийн мөрөнд.
   *
   * ⚠ Олон давхаргатай цэсэд давхаргууд нь ӨӨР ӨӨР зүйл байж болно:
   * хамгаалалтын цэсэд тэдгээр нь БҮС (тэжээгдэл · хязгаарлалт ·
   * хориглолт) тул "Бүс" гэж нэрлэгдэнэ. Нэг нэрээр нэрлэвэл аль
   * нэгэнд нь худал болох тохиолдолд л бүртгэлээс өгнө.
   * ⚠⚠ ТААМАГЛАЖ НЭРЛЭХГҮЙ: булгийн цэсийг "Хувилбар" гэж нэрлэсэн
   * нь ХУДАЛ байсан — тэнд цэг нь БУЛАГ, олон өнцөгт нь түүний БҮС
   * бөгөөд аль аль нь нөгөөгөө орлодоггүй (эх сурвалжийн эзэн,
   * 2026-09-30). Эргэлзвэл анхдагчийг үлдээ.
   * ⚠ Өгөөгүй бол "Давхарга" — техникийн ч гэсэн ҮРГЭЛЖ үнэн.
   */
  layerLabel?: string;
  /**
   * ТАЛБАРААР ШҮҮХ УНЖДАГ ЦЭС гарах эсэх (анхдагчаар гарна).
   *
   * ⚠⚠ Ногоон бүсийн хэлтэст `false` (хэрэглэгч, 2026-09-29, зургаар:
   * "энийг хасъя" — "Эх үүсвэрийн нэр" цэсийг заасан). Тэр хэлтсийн
   * диаграмууд `tidy` цэгцлэлтийн дараа өөрсдөө шүүдэг болсон:
   * хөндлөн хүснэгтийн мөр, багана, нүд, зурвасын мөр бүр товшигдоно.
   * Иймд унждаг цэс нь ЯГ ижил сонголтыг хоёр дахь удаа санал болгож,
   * шүүлтүүрийн мөрийг дүүргэж байв.
   * ⚠ Ой, амьтан, үнэлгээний хэлтэст ХЭВЭЭР: тэдгээрийн диаграмд
   * товшилт бий ч "ЮУГААР шүүж болох вэ" гэдгийг цэс л харуулдаг
   * (2026-09-15-ны шийдвэр) — тэнд цэсгүй бол шүүх боломжийг олохын
   * тулд диаграм бүрийг уншиж гарах хэрэгтэй болно.
   * ⚠ ОНЫ цэс (`series`) нь ХӨНДӨГДӨХГҮЙ: тэр нь мөр шүүдэггүй,
   * ХАРУУЛАХ цуваагаа сонгодог өөр төрлийн хяналт.
   * ⚠ Давхаргын өнгөт тэмдэг нь цэсний бүлгийн угтвар тул цэс
   * байхгүй бол өөрөө ч гарахгүй (`!cuts.length && !years.length`).
   */
  fieldMenus?: boolean;
  /**
   * ЛАТИНААР буусан домэйны утгыг харагдах хэлбэрт нь буулгана.
   *
   * ⚠ Энэ нь ОРЧУУЛГА БИШ, бичиглэлийн засвар: эх сурвалж монгол үгээ
   * латинаар бичсэн (`Mundul` → Мөндөл, `Dosh` → Дош) эсвэл англи
   * нэр томьёо хэрэглэсэн (`Adult`, `Baby`) тохиолдолд л хэрэглэнэ.
   * Утгын УТГЫГ өөрчлөхгүй — зөвхөн үсгийг нь.
   *
   * ⚠ Хэлтсийн БҮРТГЭЛД сууна: аль утга юу гэсэн үг болохыг эх
   * сурвалжийн эзэн л мэднэ. Хөдөлгүүр таамаглах ёсгүй.
   *
   * ⚠ Буулгалт нь ТАТАХ МӨЧИД хийгдэнэ тул диаграм, шүүлтүүр,
   * бичлэгийн дэлгэрэнгүй ГУРВУУЛАА нэг хэлбэр харуулна — зөвхөн
   * дэлгэц дээр солибол шүүлтийн түлхүүр нь зөрнө.
   */
  values?: Record<string, string>;
  /**
   * ТАЛБАРЫН АЛБАН НЭР — эх сурвалжийн шошго техникийн үед.
   *
   * ⚠⚠ Зарим давхаргын alias нь талбарын нэрээ давтдаг: булгийн
   * хамгаалалтын бүсийн `distance` нь дэлгэц дээр "distance — бичлэгийн
   * тоо" гэж ЛАТИНААР гарч, таних тэмдэгт ч "Өнгөөр ялгасан үзүүлэлт:
   * distance" гэж бичигдэж байв — "дэлгэц дээр товчлол, техникийн нэр
   * гаргахгүй" дүрмийн зөрчил.
   * ⚠ Толь нь ХЭЛТСИЙН бүртгэлд сууна: тэр талбар юу хэмждэгийг эх
   * сурвалжийн эзэн л мэднэ, хөдөлгүүр таамаглах ёсгүй (`values`,
   * `skipMeasure`-тэй нэг зарчим).
   * ⚠ Түлхүүр нь ТАЛБАРЫН НЭР (alias биш): alias нь өөрчлөгдөж болно.
   */
  fieldNames?: Record<string, string>;
  /**
   * ГАЗРЫН ЗУРГИЙН ШОШГОНД ХЭМЖЭЭ БИЧИХ ЭСЭХ (анхдагчаар бичнэ).
   *
   * ⚠ Ногоон бүсийн хэлтэст `false` (хэрэглэгч, 2026-09-30: "mapiin
   * label зөвхөн нэр харагдана, талбай харагдахгүй"). Шошгын үүрэг
   * нь ТАНИУЛАХ — нэр түүнд бүрэн хариулдаг бөгөөд хажуугийн тоо нь
   * зургийг бөглөрүүлнэ. Хэмжээ нь диаграм, бичлэгийн цонхонд бий.
   * ⚠ Нэргүй давхаргад шошго ОГТ гарахгүй болно — тэр нь зөв:
   * "11.8 га" гэсэн давтагдсан тоо юуг ч танихгүй ({@link LABEL_MAX}).
   */
  labelMeasure?: boolean;
  /**
   * ЗӨВХӨН ЗУРАГТ гарах давхаргууд — диаграм үүсгэхгүй.
   *
   * ⚠ Бүх задаргаа, талбайн карт, хөндлөн хүснэгт хамт гарахгүй
   * (хэрэглэгч, 2026-09-30: булгийн хамгаалалтын бүсийн хоёр картыг
   * хоёуланг нь устгуулсан). Давхарга нь зурган дээрээ хэвээр,
   * товшиход бичлэгийн цонх нээгдэнэ.
   * ⚠ `skipField`-ЭЭС ЯЛГААТАЙ: тэр нь талбарыг ТАТАХ мөчид хасдаг
   * тул бичлэгийн цонхонд ч гарахгүй болно. Энэ нь зөвхөн ДИАГРАМЫГ
   * хаадаг — утга нь бүтнээрээ үлдэнэ.
   */
  mapOnly?: readonly string[];
  /**
   * БИЧЛЭГ гэж юуг нэрлэх вэ.
   *
   * ⚠ Ерөнхий хөдөлгүүр "бичлэг" гэж бичдэг нь техникийн үг: булгийн
   * давхаргад мөр бүр нь БУЛАГ, худгийнд ХУДАГ. Хэрэглэгч (2026-09-30)
   * тооллын баганыг "булгийн тоо" болгуулав.
   * ⚠ ХОЁР ХЭЛБЭР ЗААВАЛ: монгол хэлний харьяалахын тийн ялгалыг
   * кодоор гаргах боломжгүй ("булаг" → "булгийн"), тиймээс эх
   * сурвалжийн эзэн хоёуланг нь өгнө — `one` нь тоолсон дүнд
   * ("286 булаг"), `count` нь баганын гарчигт ("Булгийн тоо").
   */
  record?: { one: string; count: string };
  /**
   * ХЭМЖИЛТЭД ОРОХГҮЙ нэгж — талбарын БҮТЭН НЭР дээр шалгагдана.
   *
   * Бичиглэл нь жигд бус ("м³ нийт", "м3 2023", "куб.м") тул задалсан
   * нэгж дээр тааруулах гэвэл шинэ бичиглэл гарах бүрд диаграм
   * чимээгүй эргэж ирнэ.
   */
  skipUnit?: RegExp;
  /**
   * ГЕКТАРЫН БАГАНА — давхаргын дугаар → талбарын нэр.
   *
   * Хөдөлгүүр талбайн баганыг НЭР (`talbai_ga`) ба ШОШГООР
   * (", га"-гаар төгссөн) тандаг. Гэтэл зарим эх сурвалж
   * хоёрын аль альд нь ордоггүй:
   *
   * `A00_Ecology_korridor_2024`-ийн бодит талбай нь кирилл
   * **`талбай`** баганад (11,562 · 5,926 · 2,863 = **20,352 га**,
   * хэлтсийн бүртгэлтэй яг таарна) — шошго нь зүгээр
   * "талбай" тул нэгж нь бичигдээгүй. Хажууд нь `ortson_ga`
   * ("Өртсөн талбайн хэмжээ, га") байдаг бөгөөд тэр нь
   * шошгоороо танигдана — гэвч тэр нь БҮСИЙН талбай БИШ,
   * гуравны хоёрт л бөглөгдсөн "өртсөн" хэмжээ (463 га).
   *
   * ⚠ Нэгжийг ШОШГООС ТААМАГЛАХГҮЙ: нүцгэн "талбай" нь
   * м² байж болно. Тиймээс ерөнхий дүрэмд ОРОХГҮЙ — аль
   * багана юу гэсэн үг болохыг эх сурвалжийн эзэн мэднэ тул
   * ХЭЛТСИЙН бүртгэлд сууна (`skipMeasure`-тэй нэг зарчим).
   */
  areaHa?: Record<string, string>;
};

/** Давхаргын харагдах нэр — бүртгэлд байхгүй бол үйлчилгээнийхээр */
export function layerName(
  set: LayerSet,
  id: string,
  fallback?: string,
): string {
  return set.names[id] ?? fallback?.trim() ?? id;
}

export function layerService(id: string): string {
  return `${HOSTING}/Hosted/${id}/FeatureServer`;
}

/**
 * Бүрдэл дэх давхаргын хаяг.
 *
 * Бүртгэлд бүтэн хаяг бичигдсэн бол түүнийг, үгүй бол порталын
 * жишгээр угсарсныг буцаана — дуудагч тал давхарга хаана байгааг
 * мэдэх шаардлагагүй.
 */
export function serviceOf(set: LayerSet, id: string): string {
  return set.services?.[id] ?? layerService(id);
}

