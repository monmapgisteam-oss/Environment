/**
 * Ангилал ялгах өнгөний шатлал.
 *
 * ⚠️ Платформын үндсэн дүрэм нь "дата дүрслэлийн өнгө ГАНЦ" — 20 аймаг,
 * 100 гүйцэтгэгчийг өнгөөр ялгавал утгагүй солонго болно. Энэ шатлал нь
 * ХОЁР нөхцөл зэрэг биелсэн үед л зөвшөөрөгдөнө:
 *
 *   1. Ангилал нь ЦӨӨН (зургаа хүртэл),
 *   2. Өнгө нь хэмжигдэхүүн биш ТАНИХ ТЭМДЭГ — газрын зураг дээрх
 *      обьектыг доорх диаграмтай нь холбоно.
 *
 * Энэ хоёрын аль нэг нь алдагдвал (жишээ нь бүртгэл 30 болвол) ганц
 * өнгө рүү буц.
 *
 * Өнгүүд бүгд НЭГ ГЭР БҮЛД — платформын дата өнгө болох цэнхэрийн
 * (`--data`) эргэн тойронд. Өнгөний өнцөг 195–220 хэмийн нарийхан мужид
 * л хөдөлж, ялгаа нь ГОЛДУУ ГЭРЭЛТЭЛТЭЭР гарна (L 0.90 → 0.50).
 *
 * Учир нь: солонгон палитр (улаан, ногоон, шаргал) нь өнгө бүрд өөр
 * УТГА байгаа мэт уншигдана — улаан нь аюул, ногоон нь сайн гэх мэт.
 * Ижил төрлийн обьектуудын ялгаа нь зөвхөн "аль нь аль нь вэ" гэсэн
 * танилт байх ёстой. Нэг өнгөний шатлал яг үүнийг өгнө: хоорондоо
 * ялгагдана, гэхдээ нэг зүйлийн хэдэн хувилбар гэдэг нь хадгалагдана.
 *
 * hex хэлбэрээр хадгалсан учир нь MapLibre `oklch()` уншдаггүй. Газрын
 * зураг ба диаграм ЯГ ижил утга хэрэглэх ёстой тул хоёуланд нь энэ
 * жагсаалт үйлчилнэ.
 */
export const TONE_RAMP = [
  "#93f1f0", // oklch(0.90 0.09 195)
  "#4cdbe3", // oklch(0.82 0.12 200)
  "#00c3d5", // oklch(0.74 0.14 205)
  "#00a8c1", // oklch(0.66 0.14 210)
  "#008caa", // oklch(0.58 0.13 215)
  "#00708e", // oklch(0.50 0.11 220)
];

/**
 * Индексээс өнгө — шатлалын дагуу дараалан.
 *
 * Индекс нь ТОГТМОЛ эх сурвалж дээр суурилах ёстой (бүртгэлийн дугаар,
 * толь бичгийн байрлал), шүүлтийн дараах байрлал дээр БИШ — эс тэгвээс
 * шүүлтүүр солиход обьектууд өнгөө солино.
 */
export function rampColor(index: number): string {
  return TONE_RAMP[index % TONE_RAMP.length];
}

/**
 * `count` ширхэг ангилалд шатлалыг ЖИГД тарааж өгнө.
 *
 * Дөрвөн ангиллыг шатлалын эхний дөрөвт хийвэл сүүлийн хоёр өнгө
 * ашиглагдахгүй үлдэж, ялгаа нь шаардлагагүй бага болно. Тараавал
 * хамгийн цайвар ба хамгийн бараан хоёрын хооронд бүх мужийг эзэлнэ.
 */
export function spreadRamp(count: number): string[] {
  if (count <= 1) return [TONE_RAMP[2]];
  const last = TONE_RAMP.length - 1;
  return Array.from({ length: count }, (_, i) =>
    TONE_RAMP[Math.round((i / (count - 1)) * last)],
  );
}
