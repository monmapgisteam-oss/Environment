/** Хүрээ — цагирагийн шалгалтаас өмнө хурдан хасна */
const BOX = (() => {
  let w = Infinity, s = Infinity, e = -Infinity, n = -Infinity;
  for (const poly of UB)
    for (const [x, y] of poly[0]) {
      if (x < w) w = x;
      if (x > e) e = x;
      if (y < s) s = y;
      if (y > n) n = y;
    }
  return { w, s, e, n };
})();

function inRing(x: number, y: number, ring: Ring): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi)
      inside = !inside;
  }
  return inside;
}

/** Цэг Улаанбаатарын хилийн дотор эсэх */
export function inUlaanbaatar(lon: number, lat: number): boolean {
  if (lon < BOX.w || lon > BOX.e || lat < BOX.s || lat > BOX.n) return false;
  return UB.some(
    (poly) => inRing(lon, lat, poly[0]) && !poly.slice(1).some((h) => inRing(lon, lat, h)),
  );
}
