export type WaterLawItem = {
  /** Баримт бичгийн нэр (номын гарчгаар). Батлагдсан баримтын нэр байвал түүнийг. */
  title: string;
  /** Батлах акт өөрөө ("Журам батлах тухай") — нэр нь батлагдсан баримтынх үед */
  act?: string;
  /** Батлагдсан огноо (номын гарчгаар) */
  date?: string;
  /** Тогтоол, тушаалын дугаар */
  no?: string;
  /** legalinfo.mn, estandard.gov.mn зэрэг эх хаяг; олдоогүй бол байхгүй */
  url?: string;
  /** Нэмэлт товч мэдээлэл ("Шинэчилсэн найруулга" гэх мэт) */
  note?: string;
  /** Хүчингүй болсон бол — юугаар */
  repealed?: string;
  /** Бүлэг доторх хэсэг (номын I, II, III хэсэг) */
  section?: string;
  /**
   * Хэрэглэгч хаягийг "(?)" гэж тэмдэглэсэн — хайлтын илэрцийн гарчгаар
   * тулгасан, баримт нь өөр байж магадгүй. ДЭЛГЭЦЭД ГАРАХГҮЙ (кодын
   * тэмдэглэл); legalinfo.mn дээр нээж баталгаажуулаад туг авна.
   */
  unsure?: true;
};

export type WaterLawGroup = {
  id: "law" | "rule" | "procedure" | "standard" | "norm";
  label: string;
  items: WaterLawItem[];
};

